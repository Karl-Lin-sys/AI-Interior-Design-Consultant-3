import { localApiOnly } from './local-api-guard.mjs';
import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI, Type } from "@google/genai";
import dotenv from "dotenv";

dotenv.config();

const app = express();
app.use('/api', localApiOnly(() => PORT));
const PORT = 3000;

// Middleware for parsing large base64 images
app.use(express.json({ limit: "20mb" }));

// Initialize Gemini
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY || "",
  httpOptions: {
    headers: {
      "User-Agent": "aistudio-build",
    },
  },
});

// API Routes
app.post("/api/reimagine", async (req, res) => {
  try {
    const { image, style } = req.body;

    if (!image || !style) {
      return res.status(400).json({ error: "Missing image or style" });
    }

    // Basic prompt for reimagining
    const prompt = `Reimagine this room in full ${style} interior design style. Maintain the basic layout and structure of the room (walls, windows, doors) but completely transform the furniture, textures, lighting, and decor to perfectly match the ${style} aesthetic. The final image should be a photorealistic, high-quality interior design render.`;

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash-image",
      contents: {
        parts: [
          {
            inlineData: {
              data: image.split(",")[1] || image, // Handle data URL or raw base64
              mimeType: "image/jpeg",
            },
          },
          {
            text: prompt,
          },
        ],
      },
      config: {
        imageConfig: {
          aspectRatio: "4:3", // Good for room photos
        },
      },
    });

    let generatedImageBase64 = "";
    let description = "";

    for (const part of response.candidates[0].content.parts) {
      if (part.inlineData) {
        generatedImageBase64 = `data:${part.inlineData.mimeType};base64,${part.inlineData.data}`;
      } else if (part.text) {
        description += part.text;
      }
    }

    if (!generatedImageBase64) {
      throw new Error("No image was generated by the model.");
    }

    res.json({ image: generatedImageBase64, description });
  } catch (error: any) {
    console.error("Error in /api/reimagine:", error);
    res.status(500).json({ error: error.message || "Failed to reimagine space" });
  }
});

app.post("/api/chat", async (req, res) => {
  try {
    const { messages, currentImage, style } = req.body;

    // Use gemini-3-flash-preview for the conversation logic
    const chatModel = ai.models.generateContent({
      model: "gemini-3-flash-preview",
      contents: messages.map((m: any) => ({
        role: m.role === "user" ? "user" : "model",
        parts: [{ text: m.content }],
      })),
      config: {
        systemInstruction: `You are an expert AI Interior Design Consultant. The user just reimagined their space in ${style} style. 
        Your goal is to help them refine this design and provide professional advice.
        If they ask for changes (e.g., "make the rug blue"), describe how those changes would look in the current style.
        Always provide 2-3 shoppable item suggestions or categories that would fit the style.
        Keep responses concise, inspiring, and professional.`,
      },
    });

    const response = await chatModel;
    res.json({ text: response.text });
  } catch (error: any) {
    console.error("Error in /api/chat:", error);
    res.status(500).json({ error: error.message || "Chat failed" });
  }
});

async function startServer() {
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "127.0.0.1", () => {
    console.log(`Server running on http://localhost:${PORT}`);
  });
}

startServer();
